const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'outputs', 'champions-2026-11');
const provinces = ['黑龙江','内蒙古','北京','上海','天津','重庆','广东','山东','浙江','江苏','河南','河北','四川','湖北','湖南','福建','云南','贵州','广西','江西','山西','陕西','辽宁','吉林','宁夏','甘肃','青海','新疆','西藏','海南','安徽'];
const base = 'https://pub-ceb3a66b5d2b48a1b9138364de4f3495.r2.dev';
const source = fs.readFileSync(path.join(root, 'data.js'), 'utf8');
const match = source.match(/window\.MATERIALS\s*=\s*([\s\S]*?);\s*$/);
if (!match) throw new Error('Cannot parse data.js');
const materials = JSON.parse(match[1]);
if (materials.some(x => x.category === '高考状元')) throw new Error('Existing champion data requires review');
const manifest = [], report = [];
async function compressed(input, target, width, initialQuality) {
  for (const quality of [initialQuality, 85, 78, 70, 62, 54].filter((q, i, a) => a.indexOf(q) === i && q <= initialQuality)) {
    const img = sharp(input).rotate();
    if (width) img.resize({width, withoutEnlargement:true});
    const buffer = await img.webp({quality}).toBuffer();
    if (buffer.length < 1000000) { fs.writeFileSync(target, buffer, {flag:'wx'}); return {bytes:buffer.length,quality}; }
  }
  throw new Error(`Cannot reach size limit without resizing: ${input}`);
}
async function main() {
  for (const year of ['2024','2025','2026']) {
    const dir = path.join(root, year, `${year}_高考状元`);
    for (const name of fs.readdirSync(dir).sort((a,b)=>a.localeCompare(b,'zh-CN'))) {
      const relative = path.join(year, `${year}_高考状元`, name);
      const file = path.join(root, relative);
      const rawName = path.parse(name).name;
      const province = provinces.find(p=>rawName.startsWith(p));
      if (!province) throw new Error(`Unrecognized province: ${name}`);
      const region = rawName.slice(province.length).replace(/^(省|市|自治区)/, '').split('状元')[0];
      const championLevel = /[市州区县盟旗]/.test(region) ? 'city' : 'province';
      const id = `${year}-${crypto.createHash('md5').update(relative).digest('hex').slice(0,12)}`;
      const sourcePath = './' + relative.split(path.sep).map(encodeURIComponent).join('/');
      const md = await sharp(file).metadata();
      const urls = {};
      for (const [kind, width, quality, field] of [['originals',null,92,'imageUrl'],['previews',1400,82,'previewUrl'],['thumbs',520,76,'thumbUrl']]) {
        const folder = path.join(output, kind); fs.mkdirSync(folder,{recursive:true});
        const key = `${kind}/${id}-champion.webp`;
        const target = path.join(folder, `${id}-champion.webp`);
        const result = await compressed(file,target,width,quality);
        manifest.push({key,file:path.relative(root,target).replace(/\\/g,'/'),contentType:'image/webp'});
        urls[field] = `${base}/${key}`;
        report.push({year,name,province,championLevel,kind,width:md.width,height:md.height,...result});
      }
      materials.push({id,year,category:'高考状元',content_type:'gaokao_champion',subject:null,province,score:null,totalScore:null,school:null,studentName:null,title:rawName,fileName:name,rawName,sourcePath,...urls,tags:[year,'高考状元',province],searchableText:`${rawName} ${year} 高考状元 ${province}`,improvementScore:null,feedbackIndex:null,sortIndex:materials.length,championLevel});
    }
  }
  fs.writeFileSync(path.join(output,'upload-manifest.json'),JSON.stringify({generatedAt:new Date().toISOString(),publicBaseUrl:base,files:manifest},null,2),{flag:'wx'});
  fs.writeFileSync(path.join(output,'data.r2.js'),`/* Generated by scripts/build-champion-assets.js */\nwindow.MATERIALS = ${JSON.stringify(materials,null,2)};\n`,{flag:'wx'});
  fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2),{flag:'wx'});
  console.log(JSON.stringify({images:report.length/3,files:manifest.length,maxBytes:Math.max(...report.map(x=>x.bytes)),province:report.filter(x=>x.kind==='originals'&&x.championLevel==='province').length,city:report.filter(x=>x.kind==='originals'&&x.championLevel==='city').length}));
}
main().catch(e=>{console.error(e);process.exitCode=1});
